@app.get("/api/predict/algal-bloom")
def predict_algal_bloom():

    temperature = random.uniform(27, 32)
    chlorophyll = random.uniform(1, 5)

    risk_score = 0

    if temperature > 29:
        risk_score += 40

    if chlorophyll > 3:
        risk_score += 40

    if risk_score >= 60:

        risk = "High"

    elif risk_score >= 30:

        risk = "Moderate"

    else:

        risk = "Low"


    return {

        "prediction": "Algal Bloom Risk",

        "risk": risk,

        "risk_score": risk_score,

        "temperature": round(temperature, 2),

        "chlorophyll": round(chlorophyll, 2),

        "message":
            "Prediction generated by the Python AI backend."
    }


