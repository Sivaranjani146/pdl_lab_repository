@app.get("/api/predict/anomaly")
def detect_anomaly():

    temperature = random.uniform(25, 33)
    turbidity = random.uniform(2, 15)

    anomaly = False

    if temperature > 31:

        anomaly = True

    if turbidity > 12:

        anomaly = True


    if anomaly:

        message = "Environmental anomaly detected."

    else:

        message = "No major environmental anomaly detected."


    return {

        "anomaly_detected": anomaly,

        "temperature": round(temperature, 2),

        "turbidity": round(turbidity, 2),

        "message": message
    }


