@app.post("/api/ocean-data")
def add_ocean_data(
    location: str,
    temperature: float,
    salinity: float,
    turbidity: float,
    chlorophyll: float,
    ph: float,
    db: Session = Depends(get_db)
):

    new_data = OceanData(

        location=location,

        temperature=temperature,

        salinity=salinity,

        turbidity=turbidity,

        chlorophyll=chlorophyll,

        ph=ph
    )

    db.add(new_data)

    db.commit()

    db.refresh(new_data)

    return {

        "message": "Ocean data saved successfully",

        "id": new_data.id,

        "location": new_data.location,

        "temperature": new_data.temperature,

        "salinity": new_data.salinity,

        "turbidity": new_data.turbidity,

        "chlorophyll": new_data.chlorophyll,

        "ph": new_data.ph
    }
